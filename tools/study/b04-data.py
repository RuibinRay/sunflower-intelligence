#!/usr/bin/env python3
"""Generate assets/js/data/study/b04/data.js, the new data B04 Descriptive and Inferential Statistics uses (everything else
comes from B01's and B03's cases). Every value is fictional. NumPy's PCG64 generator with fixed seeds, so the file can be
rebuilt exactly; the seeds were chosen so each dataset teaches its point (noted below), and lessons and the project read
their figures from case.js, never from this script.

Run:  python3 tools/study/b04-data.py
"""
from pathlib import Path
import json
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'assets/js/data/study/b04/data.js'

r = np.random.default_rng(11)
# Lessons. Kilnworth's 1 kg bags: 40 weighed by Ana in October (machine set to 1,004 g, SD 3 g, on Kilnworth's sheet).
KG_BAGS = np.round(r.normal(1003.0, 3.1, 40), 1)
# Set-up minutes for 24 catering events drawn at random from the autumn's bookings.
SETUP = np.round(r.normal(38, 9, 24)).astype(int)
# Twelve barista-workshop trainees' latte-art scores (out of 20) before and after the two-hour workshop: the scores vary a
# lot between trainees and little within, so a paired test finds what a two-sample test misses.
r4 = np.random.default_rng(4)
PRE = np.clip(np.round(r4.normal(10, 3.4, 12)), 2, 18).astype(int)
POST = np.clip(PRE + np.round(r4.normal(1.7, 1.3, 12)), 2, 20).astype(int)

# Project (lessons must not use these). The November–December courier trial: business days to delivery.
r5 = np.random.default_rng(11)
_ = r5.normal(size=40 + 24 + 24)                      # keep the courier draws independent of the lesson data above
SWIFT = np.clip(np.round(r5.normal(2.6, 1.0, 64)), 1, 6).astype(int)
PBIRD = np.clip(np.round(r5.normal(2.15, 0.85, 58)), 1, 6).astype(int)
# Workshop satisfaction (0–10) by format, 2026.
WS = [np.clip(np.round(r5.normal(m, s, n)), 0, 10).astype(int) for m, s, n in [(8.4, 1.2, 18), (7.1, 1.6, 22), (7.9, 1.3, 15)]]

def arr(a): return json.dumps([float(x) if isinstance(x, (float, np.floating)) and not float(x).is_integer() else int(x) for x in a])
js = f"""// data.js — generated by tools/study/b04-data.py (do not edit by hand). Fictional data for B04 Descriptive and
// Inferential Statistics; case.js describes each set and computes every figure from it.

/** Lessons: 40 of Kilnworth Roasting's 1 kg bags of House Blend, weighed by Ana in October 2026 (grams). */
export const KG_BAGS = {arr(KG_BAGS)};
/** Lessons: set-up time in minutes for 24 catering events drawn at random from the autumn's bookings. */
export const SETUP_MINUTES = {arr(SETUP)};
/** Lessons: latte-art scores (out of 20) of 12 workshop trainees before and after the two-hour workshop, same order. */
export const LATTE_PRE = {arr(PRE)};
export const LATTE_POST = {arr(POST)};

/** Project: business days to delivery in the November–December 2026 courier trial. */
export const SWIFTLINE_DAYS = {arr(SWIFT)};
export const PARCELBIRD_DAYS = {arr(PBIRD)};
/** Project: workshop satisfaction scores (0–10) in 2026 by format. */
export const WORKSHOP_IN_PERSON = {arr(WS[0])};
export const WORKSHOP_ONLINE = {arr(WS[1])};
export const WORKSHOP_HYBRID = {arr(WS[2])};
"""
OUT.write_text(js)
print(f'wrote {OUT.relative_to(ROOT)}')
