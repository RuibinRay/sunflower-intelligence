#!/usr/bin/env node
// study-video-plan.mjs — writes assets/js/data/study/FINANCE_VIDEO_PLAN.md: for every finance lesson, its video's
// length and chapters (from the storyboards tools/study.mjs builds) and the authored opening planned for it (from
// video-plan.js). Run after node tools/study.mjs:  node tools/study-video-plan.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, DATA, catalog } from './study/lib.mjs';
import { PLAN, VISUAL_KINDS, NEW_COURSES } from '../assets/js/data/study/video-plan.js';

const finance = catalog.COURSES.filter((c) => c.school === 'finance');
const lines = [];
let minutes = 0, lessons = 0, authored = 0;
const mm = (s) => `${Math.floor(s / 3600) ? `${Math.floor(s / 3600)} h ` : ''}${Math.round((s % 3600) / 60)} min`;

for (const c of finance.filter((x) => x.modules)) {
  lines.push(`### ${c.code} ${c.title}`, '', '| Lesson | Length | Chapters | Authored opening: the moment acted out | Visual | Script |', '|---|---|---|---|---|---|');
  for (const m of c.modules) {
    for (const slug of m.lessons) {
      const f = join(ROOT, `assets/data/study/video/${c.id}/${slug}.json`);
      if (!existsSync(f)) { lines.push(`| ${slug} | not built | | | | |`); continue; }
      const sb = JSON.parse(readFileSync(f, 'utf8'));
      const p = PLAN[c.id]?.[slug] || {};
      const done = existsSync(join(DATA, c.id, `${slug}.video.js`));
      minutes += sb.seconds; lessons++; if (done) authored++;
      lines.push(`| [${sb.title}](../../../../learn/finance/${c.id}/${slug}/) | ${Math.round(sb.seconds / 60)} min | ${sb.chapters.length} | ${p.moment || '(to plan)'} | ${p.visual || ''} | ${done ? 'written' : 'planned'} |`);
    }
  }
  lines.push('');
}
for (const c of finance.filter((x) => !x.modules)) {
  const mods = NEW_COURSES[c.id] || [];
  lines.push(`### ${c.code} ${c.title} (planned course)`, '', c.blurb, '');
  mods.forEach((m, i) => lines.push(`${i + 1}. *${m.title}:* ${m.lessons.join('; ')}.`));
  lines.push('', 'Each lesson gets its generated video when it is written, and an authored opening in the same review pass.', '');
}

const md = `# Finance school: the lesson video plan

Generated by \`node tools/study-video-plan.mjs\` from the storyboards and \`video-plan.js\`; don't edit by hand.

Every built finance lesson has a video that narrates the whole lesson in its page order: the opening and objectives,
every paragraph, equation, table and figure of “The idea”, “In depth” and “In practice”, each formula card symbol by
symbol, each worked example step by step, each interactive (with a pause-and-try prompt), each common mistake and
every summary point. \`tests/video.test.mjs\` fails if any of those is missing from a lesson's narration.

The next layer, lesson by lesson, is an authored opening chapter: a script written for the ear that acts out the
lesson's central moment with a custom stage visual. It replaces the generated chapter it retells, and every number
it says is recomputed in its \`checks\`.

**Now:** ${lessons} lessons, ${mm(minutes)} of narration in all (about ${Math.round(minutes / lessons / 60)} minutes a lesson at 2.6 words a second). Authored openings written: ${authored} of ${lessons}.

**Stage visuals:**
${Object.entries(VISUAL_KINDS).map(([k, v]) => `- \`${k}\`: ${v}`).join('\n')}

**Order of work:** the visuals that unlock the most lessons first (bridge, curve, growth, ledger), then the openings
course by course in study order, F00 to F06; each new F07–F13 lesson ships with its video and opening.

${lines.join('\n')}`;
writeFileSync(join(DATA, 'FINANCE_VIDEO_PLAN.md'), md);
console.log(`wrote FINANCE_VIDEO_PLAN.md: ${lessons} lessons, ${mm(minutes)}, ${authored} authored openings`);
