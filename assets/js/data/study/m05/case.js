// ---------------------------------------------------------------- segmentation: standardised needs, k-means, Ward
const needMeans = needsCols.map(mean), needSds = needsCols.map(sd);
const Z = standardise(needsCols).rows;                       // respondents × 8, each need to mean 0, sd 1
const KS = [2, 3, 4, 5, 6, 7, 8];
const fits = KS.map((k) => { const km = kmeans(Z, k, { restarts: 20 }); return { k, km, inertia: km.inertia, silhouette: silhouette(Z, km.labels) }; });
const K = 5, chosen = fits.find((f) => f.k === K).km;
const labels = chosen.labels;
const members = (g) => labels.map((l, i) => (l === g ? i : -1)).filter((i) => i >= 0);

// names: each segment is named by reading its profile (its highest indexes against the average); the planted type that
// dominates it is used only to keep the names stable when the data are regenerated, and IDENTITIES checks that each
// name's needs are that segment's highest indexes
const majority = (g) => { const c = new Array(5).fill(0); members(g).forEach((i) => c[trueType[i]]++); return c.indexOf(Math.max(...c)); };
const segType = Array.from({ length: K }, (_, g) => majority(g));
const NAME_OF_TYPE = ['Craft and local', 'Value routine', 'On the go', 'Mindful', 'Explorers'];
const SEGMENT_NAMES = segType.map((t) => NAME_OF_TYPE[t]);
const index = indexVsAverage(needsCols, labels, K).map((row) => row.map((v) => Math.round(v)));
const sizes = segmentSizes(labels, K, spend);
const segMeans = Array.from({ length: K }, (_, g) => needsCols.map((c) => mean(members(g).map((i) => c[i]))));
const crosstab = (attr, levels) => Array.from({ length: K }, (_, g) => levels.map((_, l) => members(g).filter((i) => attr[i] === l).length));
const ct = { age: crosstab(age, LEVELS.age), source: crosstab(source, LEVELS.source), income: crosstab(income, LEVELS.income), area: crosstab(area, LEVELS.area), household: crosstab(household, LEVELS.household) };
const chi = Object.fromEntries(Object.entries(ct).map(([k, t]) => [k, chisqIndependence(t)]));
const wardLink = ward(Z), wardLabels = cutTree(wardLink, K).labels;
const anova = NEEDS.map((_, j) => anova1(Array.from({ length: K }, (_, g) => members(g).map((i) => needsCols[j][i]))));

// the typing tool: assign a new respondent to the nearest segment centre, from all eight needs or from a short set
const FKEY = anova.map((a, j) => ({ j, F: a.F })).sort((a, b) => b.F - a.F);
const SHORT = FKEY.slice(0, 4).map((x) => x.j).sort((a, b) => a - b);      // the four needs that separate segments most
const shortCentres = chosen.centres.map((c) => SHORT.map((j) => c[j]));
const typedShort = PM.nearestCentroid(shortCentres, Z.map((r) => SHORT.map((j) => r[j])));
// hold-out check: segment the first 480 respondents, then type the other 160 with those centres
const TRAIN = 480;
const kmTrain = kmeans(Z.slice(0, TRAIN), K, { restarts: 20 });
const typedHold = PM.nearestCentroid(kmTrain.centres, Z.slice(TRAIN));
const perms = (n) => (n === 1 ? [[0]] : perms(n - 1).flatMap((p) => Array.from({ length: n }, (_, i) => [...p.slice(0, i), n - 1, ...p.slice(i)])));
const bestMatch = (a, b, k) => perms(k).reduce((best, p) => { const acc = PM.agreement(a.map((v) => p[v]), b); return acc > best.acc ? { acc, p } : best; }, { acc: -1, p: null });
const holdMatch = bestMatch(typedHold, labels.slice(TRAIN), K);
const holdTruth = bestMatch(typedHold, trueType.slice(TRAIN), K);   // against the planted kinds: what Ana couldn't check

// the local-loyalty scale: Cronbach's alpha (sample variances), and each segment's mean scale score
const loyalTotal = RESPONDENTS.map((r) => sum(r.loyal));
const variance = (xs) => sd(xs) ** 2;
const alphaLoyal = (3 / 2) * (1 - sum(loyalCols.map(variance)) / variance(loyalTotal));

// ---------------------------------------------------------------- targeting inputs
/** Ana's view of Lantern's strengths on the eight needs (+1 strong, 0 average, −1 weak), for the fit score. */
export const LANTERN_STRENGTHS = [1, -1, -1, 1, 0, 0, 1, 1];
/** Ana's estimates (fictional) of each kind of drinker's growth in Harbour City over the next three years, % a year. */
export const GROWTH_BY_NAME = { 'Craft and local': 6, 'Value routine': 1, 'On the go': 4, 'Mindful': 7, 'Explorers': 9 };
/** Lantern's gross margin per $ of sales by what a segment buys most (fictional, Ana's accounts): cafés and beans. */
export const MARGIN = 0.38;
const fit = needsFit(chosen.centres, LANTERN_STRENGTHS);

// ---------------------------------------------------------------- the perceptual map
const records = RESPONDENTS.flatMap((r) => r.rated.map((b, k) => ({ brand: b, ratings: r.ratings[k] })));
const { means: brandMeansM, counts: brandCounts } = PM.brandMeans(records, BRANDS.length, NEEDS.length);
const map = PM.perceptualMap(brandMeansM);
const segIdeal = Array.from({ length: K }, (_, g) => idealCols.map((c) => mean(members(g).map((i) => c[i]))));
const allIdeal = idealCols.map(mean);
const idealPts = segIdeal.map((p) => map.project(p));
const dist = PM.idealDistances(map, segIdeal);
const nearestRival = dist.map((row) => { const rivals = row.map((d, b) => ({ d, b })).filter((x) => x.b !== 0).sort((a, b) => a.d - b.d); return rivals[0]; });

// Cold Brew intent by segment: top two boxes (definitely or probably would buy)
const top2 = (is) => is.filter((i) => coldbrew[i] <= 2).length / is.length;

