const sum = (xs) => xs.reduce((a, b) => a + b, 0);
const mean = (xs) => sum(xs) / xs.length;
const sd = (xs) => { const m = mean(xs); return Math.sqrt(sum(xs.map((v) => (v - m) ** 2)) / (xs.length - 1)); };
