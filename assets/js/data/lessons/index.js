// lessons/index.js — the lesson plates, in reading order. One file per lesson (<id>.js, id = the Learn skill id).
//
// A lesson file default-exports:
//   id, title, minutes, hook                    hook = one sentence, also the page's description
//   idea:    [html, …]                           2–3 short paragraphs: the concept in plain words
//   formula: { html, terms: [[symbol, meaning]], note? }
//   example: { setup, steps: [html, …], result } a worked example; every printed number is reproduced in `checks`
//   mistake: { title, html }                     the most common error, with the wrong number it produces
//   remember: [html, html, html]
//   calc:    { title, intro, inputs: [{ id, label, min, max, step, value, fmt: 'pct'|'money'|'num'|'int', unit?, digits? }],
//              compute(values) -> { headline: { value, label }, rows: [[label, value]], note } | { error } }
//   tool:    { href (from the site root, e.g. 'finance/valuation/#dcf'), label }
//   checks:  [{ what, value (computed), shown (as printed), tol }]
//   sources?: [html]
// Pages are generated by tools/lessons.mjs; tests/lessons.test.mjs checks every lesson.

export const ORDER = [
  // Finance
  'tvm', 'wacc', 'invest', 'bonds', 'stocks', 'options', 'mrisk', 'credit',
  // Business analytics
  'describe', 'regression', 'classify', 'mlsup', 'mlunsup', 'forecast',
  // Marketing
  'pricing', 'segment', 'markets', 'growth',
  // How I build the models
  'validation',
];

/** Load every lesson that exists (Node or browser). */
export async function loadAll({ strict = true } = {}) {
  const out = [];
  for (const id of ORDER) {
    try { out.push((await import(`./${id}.js?v=17`)).default); } catch (e) { if (strict) throw new Error(`lesson ${id}: ${e.message}`); }
  }
  return out;
}
